/**
 * M10 WP5: writes the owner's VoiceOver listening sheet, `docs/design/a11y-passes/M10-listening-pass.md`,
 * from the step tables of every screen-reader script (`app/a11y/src/index-steps.ts`), so the sheet
 * cannot drift from what the scripts check. The set-up block is the README's, copied (between its
 * `sheet:setup` markers), so it is written once.
 *
 * `npm run a11y:sheet` writes the file; `npx tsx scripts/a11y-sheet.ts --check` exits 1 when it is out of
 * date. `app/test/a11y-sheet.test.ts` does the same comparison in vitest. The output holds no date
 * and no commit, so it changes only when a step or this script does. Edit those, not the sheet.
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { SCRIPTS, type ScriptDef } from '../app/a11y/src/index-steps.ts';

const ROOT = resolve(import.meta.dirname, '..');
export const SHEET_PATH = resolve(ROOT, 'docs/design/a11y-passes/M10-listening-pass.md');
export const README_PATH = resolve(ROOT, 'docs/design/a11y-passes/README.md');
export const SITE = 'https://chrisdevine00.github.io/optcg-sim/';

const cell = (s: string) =>
  s
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ')
    .trim();

/** The README's VoiceOver set-up block, verbatim. Throws if its markers are gone. */
export function setupBlock(readme: string): string {
  const m = /<!-- sheet:setup -->\n([\s\S]*?)\n<!-- \/sheet:setup -->/.exec(readme);
  if (!m) throw new Error('README.md has no <!-- sheet:setup --> block');
  return m[1]!;
}

/** The row for one step: the id first, so a test can count it. */
export const stepRow = (id: string, doText: string, expect: string) =>
  `| \`${cell(id)}\` | ${cell(doText)} | ${cell(expect)} |  |  |`;

function script(s: ScriptDef): string[] {
  return [
    `## ${s.name}: ${s.title}`,
    '',
    `Specified in accessibility.md ${s.section}. Start at: ${SITE}${s.start}`,
    '',
    s.intro,
    '',
    '| Step | Do | Expect | Result | Heard |',
    '| --- | --- | --- | --- | --- |',
    ...s.steps.map((t) => stepRow(t.id, t.do, t.expect)),
    '',
  ];
}

/** The whole sheet, as a string (what the file must contain). */
export function renderSheet(readme = readFileSync(README_PATH, 'utf8')): string {
  const out: string[] = [
    '# M10 listening pass: VoiceOver with Safari, by hand',
    '',
    'Generated by `npm run a11y:sheet` from the scripts in `app/a11y/src` (`scripts/a11y-sheet.ts`). Do not edit this file: change a step or the generator, then regenerate. A test fails when it is out of date.',
    '',
    'About 90 minutes, in two sittings: M3, L, M7 and M8 in the first; M9, M10 and the keyboard game in the second. Write the results here, or hand the filled sheet to the agent, which writes `<script>-voiceover-safari.md` records from it. Severity 3 and 4 findings block the milestone; say which any problem is.',
    '',
    '| Fill in | |',
    '| --- | --- |',
    '| Date | |',
    '| Who | |',
    '| macOS version | |',
    '| Safari version | |',
    '| VoiceOver version (VoiceOver Utility, or the macOS version) | |',
    '| Build id (About page, Version) | |',
    '| Address used | |',
    '',
    '## Set up',
    '',
    setupBlock(readme),
    '',
    ...SCRIPTS.flatMap(script),
    '## K: A whole game against the Warlord, by keyboard alone',
    '',
    `The one item no script covers (accessibility.md §11.7; the S3 kit's task 3.7 is the same game with an invitee). Open ${SITE}play, choose the Warlord as the opponent, and play a full game with the keyboard only and VoiceOver on. Do not use the pointer; if you must, write what for. Use \`?\` for the shortcut sheet if you get stuck.`,
    '',
    '| Step | Do | Expect | Result | Heard |',
    '| --- | --- | --- | --- | --- |',
    stepRow(
      'K1',
      'Play a whole game against the Warlord with the keyboard only; note every key that did nothing and every time you could not tell what had happened',
      'The game ends with a result that is spoken, nothing needed the pointer, every decision and every opponent move was spoken in a sentence, and you never had to leave the board to find out whose turn it was',
    ),
    '',
  ];
  return out.join('\n');
}

function main() {
  const text = renderSheet();
  if (process.argv.includes('--check')) {
    let cur = '';
    try {
      cur = readFileSync(SHEET_PATH, 'utf8');
    } catch {
      // missing counts as out of date
    }
    if (cur !== text) {
      console.error('M10-listening-pass.md is out of date: run `npm run a11y:sheet`.');
      process.exit(1);
    }
    console.log('M10-listening-pass.md is up to date.');
    return;
  }
  writeFileSync(SHEET_PATH, text);
  console.log(
    `Wrote ${SHEET_PATH}: ${SCRIPTS.reduce((n, s) => n + s.steps.length, 0)} steps in ${SCRIPTS.length} scripts, plus the keyboard game.`,
  );
}

if (process.argv[1] && import.meta.filename === realpathSync(process.argv[1])) main();
