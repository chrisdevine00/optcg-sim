function loadCards(): CardLookup {
  const dir = new URL('../cards/data/sets/', import.meta.url);
  const byId = new Map<string, Card>();
  for (const f of readdirSync(dir)) {
    const set = JSON.parse(readFileSync(new URL(f, dir), 'utf8')) as SetFile;
    for (const c of set.cards) byId.set(c.id, c);
  }
  return (id) => byId.get(id);
}

async function main(argv: string[]): Promise<void> {
  if (argv[0] === 'sus') {
    console.log(susScore(argv.slice(1).map(Number)));
    return;
  }
  await loadAllScripts();
  const meta = JSON.parse(
    readFileSync(new URL('../docs/research/meta-lists.json', import.meta.url), 'utf8'),
  ) as { asOf: string; archetypes: MetaArchetype[] };
  const picked = pickList(meta.archetypes, loadCards());
  if (!picked) throw new Error('no Standard-legal, fully automated list in meta-lists.json');
  const dir = new URL('../docs/design/usability/', import.meta.url);
  writeFileSync(new URL('S3-list.txt', dir), formatList(picked, meta.asOf));
  const curriculum = readFileSync(
    new URL('../docs/content/curriculum.md', import.meta.url),
    'utf8',
  );
  writeFileSync(new URL('S3-seed.json', dir), JSON.stringify(makeSeed(curriculum), null, 2) + '\n');
  console.log(
    `S3-list.txt: ${picked.archetype.name}, ${picked.list.placing} at ${picked.list.event}`,
  );
  console.log('S3-seed.json: 3 drill sessions, 3 lesson marks, no games');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  main(process.argv.slice(2)).catch((e) => {
    console.error(e);
    process.exit(1);
  });
