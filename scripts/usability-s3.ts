/**
 * The owner's session 3 kit (M10 WP9): the two files the kit hands over, and the SUS scorer.
 *
 *   npx tsx scripts/usability-s3.ts           writes docs/design/usability/S3-list.txt and S3-seed.json
 *   npx tsx scripts/usability-s3.ts sus 4 2 4 2 5 1 4 2 4 3   scores one sheet (ten answers, 1 to 5, item 1 first)
 *
 * `S3-list.txt` is one sourced tournament list from `docs/research/meta-lists.json`: the first list of
 * the first archetype whose list is Standard-legal and fully automated, in the deck importer's text
 * format. The header comment names the event, date, placing and URL (the importer ignores `#` lines);
 * it leaves out the player's name. `S3-seed.json` is an export bundle (schema `optcg-sim/export/1`)
 * whose `progress` holds three drill sessions and lesson marks and NO games: games and flags are
 * derived from saved games (M9), so a seed with games would put games the owner never played into
 * their History. The recommendation then reads "Not enough games yet", which is true.
 *
 * Pure functions are exported for `app/test/usability-s3.test.ts`; the CLI part runs only when the file
 * is the entry point. Nothing is random and nothing reads a clock: the same inputs give the same files.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { automation, loadAllScripts, playsFully, SCRIPTED_IDS, type Card } from '@optcg/cards';
import type { SetFile } from '@optcg/cards';
import { deckIssues, type CardLookup } from '@optcg/engine';

// ---------------------------------------------------------------------------------------------
// The list
// ---------------------------------------------------------------------------------------------

export interface MetaList {
  event: string;
  date: string;
  placing: string;
  url: string;
  leader: string;
  main: { id: string; count: number }[];
}
export interface MetaArchetype {
  id: string;
  leaderId: string;
  name: string;
  lists: MetaList[];
}

export interface Pick {
  archetype: MetaArchetype;
  list: MetaList;
}

/** What makes a list usable in the session: Standard-legal (no deck issue) and every card plays fully. */
export function usable(
  list: MetaList,
  lookup: CardLookup,
  scripted: ReadonlySet<string> = SCRIPTED_IDS,
): boolean {
  const main = list.main.flatMap((c) => Array.from({ length: c.count }, () => c.id));
  if (main.length !== 50) return false;
  if (deckIssues({ leader: list.leader, main }, lookup, 'standard').length > 0) return false;
  return [list.leader, ...list.main.map((c) => c.id)].every((id) => {
    const card = lookup(id);
    return card !== undefined && playsFully(automation(card as Card, scripted));
  });
}

/** The first list of the first archetype (file order) that is `usable`; null when none is. */
export function pickList(
  archetypes: readonly MetaArchetype[],
  lookup: CardLookup,
  scripted: ReadonlySet<string> = SCRIPTED_IDS,
): Pick | null {
  for (const archetype of archetypes) {
    const list = archetype.lists[0];
    if (list && usable(list, lookup, scripted)) return { archetype, list };
  }
  return null;
}

/** The importer's compact text (`4xOP17-040`, Leader as `1xOP17-039`), with a header the importer ignores. */
export function formatList(p: Pick, asOf: string): string {
  const { archetype: a, list: l } = p;
  const head = [
    `# Session 3 list: ${a.name} (${l.leader}), a tournament list as played.`,
    `# Source: ${l.placing} at ${l.event} on ${l.date}.`,
    `# ${l.url}`,
    `# From docs/research/meta-lists.json (as of ${asOf}), the first list of the first archetype that is`,
    `# Standard-legal with every card automated. Paste it into Decks, Import. Generated by`,
    `# scripts/usability-s3.ts: do not edit by hand.`,
  ];
  const cards = [{ id: l.leader, count: 1 }, ...l.main];
  return [...head, ...cards.map((c) => `${c.count}x${c.id}`)].join('\n') + '\n';
}

// ---------------------------------------------------------------------------------------------
// The seed
// ---------------------------------------------------------------------------------------------

/** A fixed past instant for the seed's sessions, so the file is the same every time it is made. */
export const SEED_AT = '2026-11-20T10:00:00.000Z';

/**
 * Three drill sessions and lesson marks, no games. Lesson ids are read from the curriculum text, so
 * a renamed lesson is caught here and not in the owner's browser. The counter and DON!! drills pass
 * their exit (8 of 10 and 7 of 10); the lethal drill does not (6 of 10): Progress then shows one
 * passed pair and one drill still open.
 */
export function makeSeed(curriculum: string): unknown {
  const lessonId = (code: string): string => {
    const m = new RegExp(`^### (${code}-[a-z0-9-]+)\\s*$`, 'm').exec(curriculum);
    if (!m) throw new Error(`curriculum has no lesson ${code}`);
    return m[1]!;
  };
  const session = (
    id: string,
    drill: 'counter' | 'don' | 'lethal',
    code: string,
    at: string,
    correct: number,
  ) => ({
    id,
    drill,
    lesson: lessonId(code),
    at,
    n: 10,
    correct,
    shown: 0,
    factor: null,
    itemIds: Array.from({ length: 10 }, (_, i) => `${drill}-seed-${i + 1}`),
  });
  return {
    schema: 'optcg-sim/export/1',
    exportedAt: Date.parse(SEED_AT),
    build: 'usability-s3-seed',
    games: [],
    reviews: [],
    timing: {},
    progress: {
      v1: {
        v: 1,
        lessons: {
          L09: { source: 'drill', passedAt: '2026-11-20T10:20:00.000Z' },
          L10: { source: 'drill', passedAt: '2026-11-20T10:10:00.000Z' },
          L11: { source: 'manual', readAt: '2026-11-20T10:30:00.000Z' },
        },
        sessions: [
          session('s3seed-counter-1', 'counter', 'L10', '2026-11-20T10:10:00.000Z', 8),
          session('s3seed-don-1', 'don', 'L09', '2026-11-20T10:20:00.000Z', 7),
          session('s3seed-lethal-1', 'lethal', 'L15', '2026-11-20T10:25:00.000Z', 6),
        ],
      },
    },
  };
}

// ---------------------------------------------------------------------------------------------
// SUS
// ---------------------------------------------------------------------------------------------

/**
 * The System Usability Scale (Brooke, 1996): ten answers, 1 (strongly disagree) to 5 (strongly agree),
 * item 1 first. Odd items (positive) contribute answer - 1, even items (negative) 5 - answer; the sum
 * times 2.5 is 0 to 100. Throws on anything but ten integers from 1 to 5.
 */
export function susScore(answers: readonly number[]): number {
  if (answers.length !== 10) throw new Error('SUS has ten items');
  let sum = 0;
  answers.forEach((a, i) => {
    if (!Number.isInteger(a) || a < 1 || a > 5) throw new Error(`item ${i + 1}: answer 1 to 5`);
    sum += i % 2 === 0 ? a - 1 : 5 - a;
  });
  return sum * 2.5;
}

