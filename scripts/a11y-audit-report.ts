/**
 * M10 WP4: turns the audit's results (`test-results/audit-<project>.json`, `audit-incomplete-<project>.json`,
 * `audit-nav.json`, `audit-keyboard-warlord.json`, written by `app/e2e/m10-audit.spec.ts` whatever the
 * verdict) into `docs/design/a11y-passes/m10-automated.md`.
 *
 * Run `npm run test:audit` (or `npx playwright test app/e2e/m10-audit.spec.ts`), then
 * `npx tsx scripts/a11y-audit-report.ts`. The document is generated: edit this script, not the output.
 */
import { chromium } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

interface Rec {
  name: string;
  path: string;
  project: string;
  size: string;
  deep: boolean;
  url: string;
  title: string;
  axe: { violations: string[]; incomplete: { id: string; nodes: number; help: string }[] };
  heading: { found: boolean; focused: boolean; text: string; noFocus: string | null };
  tabs: {
    stops: number;
    ended: string;
    fully: string[];
    partly: string[];
    offscreen: number;
    unnamed: number;
  };
  targets: {
    count: number;
    smallest: number;
    smallestName: string;
    failing: unknown[];
    spaced: number;
    inline: number;
  };
  zoom?: { factor: number; css: { w: number; h: number }; overflowX: number; clipped: string[] }[];
  spacing?: { clipped: string[]; overlaps: string[]; truncated: number };
  forced?: { sampled: number; noRing: string[]; optOut: string[] };
  reduced?: { running: string[] };
  vision?: string[];
  problems: string[];
  known?: { finding: string; why: string }[];
}

const load = <T>(file: string): T | null =>
  existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as T) : null;

const projects = ['720p', '1080p'];
const data = Object.fromEntries(
  projects.map((p) => [p, load<Record<string, Rec>>(`test-results/audit-${p}.json`)]),
) as Record<string, Record<string, Rec> | null>;
const incomplete = Object.fromEntries(
  projects.map((p) => [
    p,
    load<Record<string, { id: string; nodes: number; help: string }[]>>(
      `test-results/audit-incomplete-${p}.json`,
    ),
  ]),
);
const nav = load<Record<string, Record<string, unknown>>>('test-results/audit-nav.json');
const kb = load<{ keystrokes: number; longestTabRun: number; decisions: number; result: string }>(
  'test-results/audit-keyboard-warlord.json',
);

const git = (...a: string[]) => execFileSync('git', a, { encoding: 'utf8' }).trim();
const pw = (
  JSON.parse(readFileSync('node_modules/@playwright/test/package.json', 'utf8')) as {
    version: string;
  }
).version;
const axeV = (
  JSON.parse(readFileSync('node_modules/axe-core/package.json', 'utf8')) as { version: string }
).version;
const browser = await chromium.launch();
const chromiumV = browser.version();
await browser.close();

const names = [...new Set(projects.flatMap((p) => Object.keys(data[p] ?? {})))];
const total = projects.reduce((n, p) => n + Object.keys(data[p] ?? {}).length, 0);
const failing = projects.flatMap((p) =>
  Object.values(data[p] ?? {}).filter((r) => r.problems.length > 0),
);
const sizes = (p: string) => Object.values(data[p] ?? {})[0]?.size ?? p;
const cell = (r: Rec | undefined, f: (r: Rec) => string) => (r ? f(r) : 'not run');

const out: string[] = [];
out.push('# M10 automated WCAG 2.2 AA audit', '');
out.push(
  `Generated by \`scripts/a11y-audit-report.ts\` from \`test-results/audit-*.json\`. Commit ${git('rev-parse', '--short', 'HEAD')}, Playwright ${pw}, Chromium ${chromiumV}, axe-core ${axeV}. Do not edit by hand.`,
  '',
);
out.push(
  `**Summary: ${names.length} states at ${projects.length} sizes (${projects.map(sizes).join(' and ')}), ${total} runs; ${total - failing.length} with no problem, ${failing.length} with one or more.** Axe runs with the tags wcag2a, wcag2aa, wcag21a, wcag21aa, wcag22aa and must find zero violations; its \`incomplete\` list is below.`,
  '',
);
out.push(
  'What is automated here, and what is not: axe; the level-one heading and whether it takes focus on a route change; the Tab sweep (no stop fully hidden under another element, 2.4.11, up to 60 stops; "partly" is reported); target size (2.5.8, by box measurement and the 24 px spacing exception); and, on the eight deep states, 200% and 400% zoom (1.4.4, 1.4.10), the 1.4.12 text-spacing override, forced colours, reduced motion and, on three, colour-vision screenshots. Reading the colour-vision screenshots against accessibility §6.1 is manual (WP5). Card faces are fixed-size renderings of a printed card and are exempt from the clipped-text check (their text is whole in the accessible name and the inspector); they are counted as "truncated".',
  '',
);

out.push('## Axe, heading, Tab sweep and targets, per state and size', '');
out.push(
  '| State | Size | Axe | Heading focus | Tab stops | Obscured (full / partly) | Smallest target (px) | Under 24 px, spaced | Result |',
  '|---|---|---|---|---|---|---|---|---|',
);
for (const n of names)
  for (const p of projects) {
    const r = data[p]?.[n];
    out.push(
      `| ${n} | ${p} | ${cell(r, (x) => (x.axe.violations.length ? `${x.axe.violations.length} violation(s)` : 'pass'))} | ${cell(r, (x) => (x.heading.focused ? 'focused' : x.heading.noFocus ? `n/a: ${x.heading.noFocus}` : x.heading.found ? 'NOT focused' : 'no h1'))} | ${cell(r, (x) => `${x.tabs.stops}${x.tabs.ended === 'max' ? '+' : ''}`)} | ${cell(r, (x) => `${x.tabs.fully.length} / ${x.tabs.partly.length}`)} | ${cell(r, (x) => `${x.targets.smallest}`)} | ${cell(r, (x) => `${x.targets.spaced}`)} | ${cell(r, (x) => (x.problems.length ? `${x.problems.length} problem(s)` : 'pass'))} |`,
    );
  }
out.push('');

out.push('## Deep states: zoom, text spacing, forced colours, reduced motion', '');
out.push(
  '| State | Size | 200%: sideways scroll | 400%: sideways scroll | Clipped channels (200% / 400%) | Spacing: new clipped / overlaps / truncated | Forced colours: focus ring on first ten stops | Reduced motion: running moves |',
  '|---|---|---|---|---|---|---|---|',
);
for (const n of names)
  for (const p of projects) {
    const r = data[p]?.[n];
    if (!r?.deep) continue;
    const z2 = r.zoom?.find((z) => z.factor === 2);
    const z4 = r.zoom?.find((z) => z.factor === 4);
    out.push(
      `| ${n} | ${p} | ${z2 ? `${z2.overflowX} px` : '-'} | ${z4 ? `${z4.overflowX} px` : '-'} | ${z2?.clipped.length ?? 0} / ${z4?.clipped.length ?? 0} | ${r.spacing ? `${r.spacing.clipped.length} / ${r.spacing.overlaps.length} / ${r.spacing.truncated}` : '-'} | ${r.forced ? `${r.forced.sampled - r.forced.noRing.length} of ${r.forced.sampled}` : '-'} | ${r.reduced ? r.reduced.running.length : '-'} |`,
    );
  }
out.push('');

const optOut = new Set(
  projects.flatMap((p) => Object.values(data[p] ?? {}).flatMap((r) => r.forced?.optOut ?? [])),
);
if (optOut.size)
  out.push(
    'Elements that set `forced-color-adjust: none` (judged by a person: the information must not depend on the colour they keep): ' +
      [...optOut].map((s) => `\`${s}\``).join(', ') +
      '.',
    '',
  );

out.push('## Colour-vision screenshots', '');
const shots = projects.flatMap((p) => Object.values(data[p] ?? {}).flatMap((r) => r.vision ?? []));
out.push(
  shots.length
    ? `${shots.length} screenshots under \`.cache/m10/\` (not committed): ` +
        [...new Set(shots.map((s) => s.replace(/^.*vision-(\w+)-.*$/, '$1')))].join(', ') +
        '. Read against accessibility §6.1 in the WCAG audit document (WP5).'
    : 'None captured.',
  '',
);

out.push('## Axe incomplete (what axe could not decide)', '');
const inc = new Map<string, { nodes: number; help: string; where: Set<string> }>();
for (const p of projects)
  for (const [name, list] of Object.entries(incomplete[p] ?? {}))
    for (const i of list) {
      const e = inc.get(i.id) ?? { nodes: 0, help: i.help, where: new Set<string>() };
      e.nodes += i.nodes;
      e.where.add(name);
      inc.set(i.id, e);
    }
if (inc.size === 0) out.push('None.', '');
else {
  out.push('| Rule | Nodes (all runs) | What axe says | States |', '|---|---|---|---|');
  for (const [id, e] of [...inc].sort((a, b) => b[1].nodes - a[1].nodes))
    out.push(`| ${id} | ${e.nodes} | ${e.help} | ${[...e.where].join(', ')} |`);
  out.push(
    '',
    'The audit blocks card art, so most `color-contrast` incompletes are not art: on Learn, Progress and Rules they are `aria-hidden` status glyphs (axe cannot read them) and two partly covered links, benign; on Cards, which draws text faces, the text-face body text over its gradient is what axe cannot sample, and `scripts/contrast.ts` checks token pairs, not that. Text over real card art (WCAG 1.4.3 and 1.4.11) is checked by nothing automatic: it is a manual row of the WCAG audit document (M10 review, R15).',
    '',
  );
}

out.push('## The nine-item nav (M9 open item)', '');
if (nav) {
  out.push(
    'Measured on `/about` (the header is the same on every page with one). A "row" is a distinct top edge among the nav links; "needed" is the width the links take on one line.',
    '',
    '| Viewport (CSS px) | Rows | Nav width | Header scrolls sideways by | Page scrolls sideways by | Clipped links | Header height | Smallest link (px) |',
    '|---|---|---|---|---|---|---|---|',
  );
  for (const [label, v] of Object.entries(nav))
    out.push(
      `| ${label} | ${v['rows']} | ${v['navWidth']} | ${v['headerOverflow']} | ${v['pageOverflow']} | ${(v['truncated'] as string[]).join(', ') || 'none'} | ${v['headerHeight']} | ${v['smallestLink']} |`,
    );
  out.push('');
} else out.push('Not measured.', '');

out.push('## Keyboard-only game against the Warlord (nightly)', '');
out.push(
  kb
    ? `Last run: ${kb.keystrokes} keystrokes, longest Tab run ${kb.longestTabRun}, ${kb.decisions} decisions, result "${kb.result}". The human half is the S3 kit's task 3.7.`
    : 'Not run in this pass (`E2E_FULL=1`, nightly).',
  '',
);

const known = projects.flatMap((p) =>
  Object.values(data[p] ?? {}).flatMap((r) =>
    (r.known ?? []).map((k) => ({ ...k, project: r.project, name: r.name })),
  ),
);
if (known.length) {
  out.push('## Known findings (reported, not failing)', '');
  for (const k of known) out.push(`- (${k.project}) ${k.finding}. ${k.why}`);
  out.push('');
}

if (failing.length) {
  out.push('## Open problems', '');
  for (const r of failing) for (const p of r.problems) out.push(`- (${r.project}) ${p}`);
  out.push('');
}

writeFileSync('docs/design/a11y-passes/m10-automated.md', out.join('\n'));
console.log(
  `wrote docs/design/a11y-passes/m10-automated.md (${names.length} states, ${failing.length} runs with problems)`,
);
