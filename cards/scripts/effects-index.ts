/**
 * `npm run cards:effects-index` (PLAN §2a M6b-0, lazy per-set script chunks).
 *
 * Writes `cards/effects/<SET>/index.ts` (the set's scripts, one chunk per set in the app) and
 * `cards/effects/registry.ts` (every scripted card number, and a loader per set). Run it after adding
 * or removing a script file; `cards/test/effects-index.test.ts` fails when the files are stale.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const EFFECTS = resolve(dirname(fileURLToPath(import.meta.url)), '../effects');
const HEADER = '// Generated by `npm run cards:effects-index`. Do not edit.\n';
const ID = /^([A-Z]+\d*-\d{3})\.ts$/;

export interface Generated {
  /** Path relative to cards/effects → contents. */
  files: Map<string, string>;
}

export async function generate(dir = EFFECTS): Promise<Generated> {
  const files = new Map<string, string>();
  const sets = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  const all: string[] = [];
  const loaders: string[] = [];
  for (const set of sets) {
    const ids = readdirSync(join(dir, set))
      .map((f) => ID.exec(f)?.[1])
      .filter((x): x is string => !!x)
      .sort();
    if (ids.length === 0) continue;
    all.push(...ids);
    const name = (id: string) => id.replace('-', '_');
    files.set(
      `${set}/index.ts`,
      HEADER +
        "import type { CardScript } from '../../src/dsl.ts';\n" +
        ids.map((id) => `import { ${name(id)} } from './${id}.ts';\n`).join('') +
        `\nconst SET: readonly CardScript[] = [\n${ids.map((id) => `  ${name(id)},\n`).join('')}];\nexport default SET;\n`,
    );
    loaders.push(`  '${set}': () => import('./${set}/index.ts'),\n`);
  }
  files.set(
    'registry.ts',
    HEADER +
      "import type { CardScript } from '../src/dsl.ts';\n\n" +
      '/** Every card number with a script, without loading any script. */\n' +
      `export const SCRIPTED_ID_LIST: readonly string[] = [\n${all
        .sort()
        .map((id) => `  '${id}',\n`)
        .join('')}];\n\n` +
      '/** One loader per set folder; the app gets one chunk per set. */\n' +
      'export const SET_LOADERS: Readonly<\n  Record<string, () => Promise<{ default: readonly CardScript[] }>>\n> = {\n' +
      loaders.join('') +
      '};\n',
  );
  // Formatted as Prettier would, so `prettier --write` never makes the files look stale.
  for (const [rel, text] of files) {
    const filepath = join(dir, rel);
    const options = (await resolveConfig(filepath)) ?? {};
    files.set(rel, await format(text, { ...options, filepath }));
  }
  return { files };
}

/** Files whose contents on disk differ from the generated ones. */
export async function stale(dir = EFFECTS): Promise<string[]> {
  const out: string[] = [];
  for (const [rel, text] of (await generate(dir)).files) {
    let disk = '';
    try {
      disk = readFileSync(join(dir, rel), 'utf8');
    } catch {
      /* missing */
    }
    if (disk !== text) out.push(rel);
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  void generate().then(({ files }) => {
    for (const [rel, text] of files) writeFileSync(join(EFFECTS, rel), text);
    console.log(`wrote ${files.size} files in cards/effects`);
  });
}
